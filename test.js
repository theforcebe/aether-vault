// Aether Vault consolidated test suite. Run: node test.js
// Covers data integrity, rules, vectors, store, bought flow, analyzer,
// builder grid, headless view renders (with and without lazy data), sync crypto.
// Exits 1 on any failure; deploys are gated on this.

let pass = 0, fail = 0;
const ok = (cond, label) => {
  if (cond) { pass++; }
  else { fail++; console.log('  FAIL:', label); }
};
const section = (name) => console.log('\n[' + name + ']');

// ---------- shims ----------
global.window = {};
const mem = {};
global.localStorage = { getItem: (k) => mem[k] ?? null, setItem: (k, v) => { mem[k] = String(v); }, removeItem: (k) => { delete mem[k]; }, get length() { return Object.keys(mem).length; }, key: (i) => Object.keys(mem)[i] };
Object.defineProperty(global.localStorage, 'keys', { value: () => Object.keys(mem) });
global.location = { hash: '#/dashboard', reload: () => {} };
global.navigator = { onLine: false, userAgent: 'test-harness', clipboard: { writeText: async () => {} } };
global.document = {
  getElementById: () => null, querySelector: () => null, querySelectorAll: () => [],
  addEventListener: () => {}, createElement: () => ({ style: {}, setAttribute: () => {}, addEventListener: () => {} }),
  head: { appendChild: () => {} }, body: { appendChild: () => {}, removeChild: () => {} },
};
global.Object.keys_ls = () => Object.keys(mem);
// Object.keys(localStorage) must work for prune logic
const realKeys = Object.keys;
// (localStorage shim above is a plain object wrapper; Object.keys works on mem via spread below)

// ---------- load data + modules ----------
require('./data/collection.js'); require('./data/cards.js'); require('./data/decks.js');
require('./data/templates.js'); require('./data/brain.js'); require('./data/vectors.js'); require('./data/commanders.js');
try { require('./data/manifest.js'); } catch (e) { /* generated by bake */ }
try { require('./data/combos.js'); } catch (e) { /* optional bundle */ }
try { require('./data/commanders-cards.js'); } catch (e) { /* optional bundle */ }
const fs = require('fs');
for (const [f, g] of [['scryfall', 'Scry'], ['rules', 'Rules'], ['vector', 'Vec'], ['store', 'Store'], ['sync', 'Sync'], ['analyze', 'Analyze'], ['builder', 'Builder'], ['pilot', 'Pilot'], ['ui', 'UI']]) {
  eval(fs.readFileSync('js/' + f + '.js', 'utf8').replace('const ' + g + ' =', 'global.' + g + ' ='));
}
global.App = { go: () => {}, refresh: () => {}, render: () => {}, ensureData: () => Promise.resolve() };

(async () => {
  // ---------- data integrity ----------
  section('DATA');
  const B = window.VAULT_BRAIN, V = window.VAULT_VECTORS, C = window.VAULT_COMMANDERS, T = window.VAULT_TEMPLATES;
  ok(B && B.decksTotal >= 1900, 'brain has 1900+ decks (' + (B && B.decksTotal) + ')');
  ok(B && Object.keys(B.archetypes).length >= 14, 'brain covers 14 archetypes');
  ok(B && Object.values(B.archetypes).every((a) => a.comp.lands >= 28 && a.comp.lands <= 42), 'brain comps sane');
  ok(V && Object.keys(V.cards).length > 2500, 'vectors cover 2500+ cards (' + (V && Object.keys(V.cards).length) + ')');
  ok(V && V.decks.length > 1500, 'vectors cover 1500+ decks');
  ok(C && C.commanders.length >= 600, 'directory has 600+ commanders (' + (C && C.commanders.length) + ')');
  ok(T && T.archetypes.length >= 14, 'templates cover archetypes');
  ok(window.VAULT_MANIFEST && Object.keys(window.VAULT_MANIFEST.files).length >= 5, 'manifest present');
  const CB = window.VAULT_COMBOS;
  ok(CB && CB.combos.length >= 800, 'combo bake present (' + (CB && CB.combos.length) + ')');
  ok(CB && CB.combos.filter((x) => x.c.length === 2).length >= 400, 'two-card combos covered');
  for (const [k, a] of Object.entries(B ? B.archetypes : {})) {
    if (a.compByBracket) for (const [bk, c] of Object.entries(a.compByBracket)) {
      if (!(c.lands >= 25 && c.lands <= 45 && c.n >= 15)) { ok(false, 'compByBracket sane ' + k + '/' + bk); break; }
    }
  }

  // ---------- rules ----------
  section('RULES');
  ok(Rules.GAME_CHANGERS.length === 53, 'GC list is 53 cards (' + Rules.GAME_CHANGERS.length + ')');
  ok(Rules.BRACKETS.length === 5, 'five brackets');
  const fakeTreasure = { o: 'when this creature dies, create a treasure token. (it\'s an artifact with "{t}, sacrifice this artifact: add one mana of any color.")', t: 'creature', mv: 2 };
  ok(!Rules.isRamp(fakeTreasure), 'reminder text does not fake ramp');
  ok(Rules.isRamp({ o: 'search your library for a basic land card, put it onto the battlefield tapped', t: 'sorcery', mv: 2 }), 'real ramp detected');
  const pairNames = new Set(['exquisite blood', 'sanguine bond']);
  ok(Rules.COMBO_PAIRS.some((p) => pairNames.has(p.a.toLowerCase()) && pairNames.has(p.b.toLowerCase())), 'blood/bond combo pair known');
  const merged = Rules.comboPairs();
  ok(merged.length >= 400, 'spellbook merge widens combo knowledge (' + merged.length + ' pairs)');
  ok(merged.some((p) => p.tag && Rules.comboIsFast(p)), 'spellbook tags drive fast-combo detection');
  ok(!merged.some((p) => p.tag === 'B'), 'banned combos excluded');

  // ---------- vectors ----------
  section('VECTORS');
  const aristo = Vec.deckVector(['Blood Artist', 'Viscera Seer', 'Zulaport Cutthroat', 'Grave Pact', 'Carrion Feeder', 'Village Rites', "Ashnod's Altar", 'Pitiless Plunderer', 'Mayhem Devil', 'Skullclamp', 'Meren of Clan Nel Toth', 'Sakura-Tribe Elder']);
  ok(aristo && aristo.length > 4, 'deck vector has dims (' + (aristo ? aristo.length : 0) + ')');
  const near = Vec.nearestDecks(aristo, 3);
  ok(near.length === 3 && near[0].score > 0.4, 'aristocrat query finds real decks (' + (near[0] && Math.round(near[0].score * 100)) + '%)');
  const why = Vec.because('Dictate of Erebos', new Set(['bloodartist', 'visceraseer', 'gravepact']), 3);
  ok(why.length > 0, 'because() explains suggestions');

  // ---------- store: csv, baseline ticker, backup roundtrip ----------
  section('STORE');
  const csv = 'Name,Set code,Collector number,Quantity,Foil,Binder Name\n"Sol Ring",C21,263,2,normal,Extras\n"Island",ONE,262,5,normal,Extras\n';
  const rowsParsed = Store.parseManaBoxCsv(csv);
  ok(rowsParsed.length === 2 && rowsParsed[0].q === 2, 'ManaBox CSV parses');
  let threw = false;
  try { Store.parseManaBoxCsv('Nope,Headers\n1,2'); } catch (e) { threw = true; }
  ok(threw, 'bad CSV rejected');

  Store.importBackup(JSON.parse(fs.readFileSync('C:/Users/keane/Downloads/aether-vault-keanen.json', 'utf8')));
  ok(Store.rows().length > 1500, 'personal backup restores (' + Store.rows().length + ' rows)');
  ok(Store.state.userdecks.length >= 7, 'user decks restored (' + Store.state.userdecks.length + ')');
  const total1 = Store.collectionTotal();
  const dump = Store.backupObject ? Store.backupObject() : JSON.parse(JSON.stringify(Sync.currentVault()));
  for (const k of Object.keys(mem)) delete mem[k];
  Store.load ? Store.load() : null;
  Store.importBackup(dump);
  ok(Math.abs(Store.collectionTotal() - total1) < 0.01, 'backup roundtrip preserves value');

  // ---------- bought flow ----------
  section('BOUGHT');
  const meren = Store.state.userdecks.find((d) => d.name.includes('Meren'));
  ok(!!meren, 'Meren deck present');
  const missing = Store.missingFromCollection(Store.deckView(meren.id).cards);
  ok(missing.length > 0 && missing.every((m) => !/^(plains|island|swamp|mountain|forest|wastes)$/i.test(m.n)), 'missing list excludes basics');
  const beforeRows = Store.rows().filter((r) => r.b === 'Purchased').length;
  Store.addPurchased(missing.slice(0, 2));
  const afterMissing = Store.missingFromCollection(Store.deckView(meren.id).cards);
  ok(afterMissing.length === missing.length - 2, 'purchases shrink the missing list');
  ok(Store.rows().filter((r) => r.b === 'Purchased').length === beforeRows + 2, 'purchases land in Purchased binder');

  // ---------- analyzer ----------
  section('ANALYZER');
  const db = require('C:/Users/keane/deck-overhaul/data/db.json');
  const dv = Store.deckView(meren.id);
  const factMap = {};
  for (const c of dv.cards) {
    const f = db.cards[Store.norm(c.n)];
    if (f) factMap[c.n.toLowerCase()] = { o: (f.oracle || '').toLowerCase(), t: (f.type_line || '').toLowerCase(), mv: f.mv || 0, ci: f.ci || '' };
  }
  const rep = Analyze.analyzeWithFacts({ cards: dv.cards, ci: dv.ci }, factMap);
  ok(rep.bracket >= 1 && rep.bracket <= 5, 'bracket in range (' + rep.bracket + ')');
  ok((rep.brainMatches || []).length > 0, 'brain matches found');
  ok((rep.similarDecks || []).length > 0, 'similar real decks found');
  ok(rep.brainSuggestions && rep.brainSuggestions.items.length >= 5, 'suggestions produced');
  ok(rep.brainSuggestions.items.some((i) => i.because && i.because.length), 'suggestions carry because-clauses');

  // ---------- complete-my-deck + budget ceiling ----------
  section('COMPLETE');
  const partial = Store.createUserDeck('Test partial', Store.deckView(meren.id).cards.slice(0, 45).map((c) => ({ n: c.n, q: 1, sid: c.sid })));
  Store.setUserCommander(partial.id, 'Meren of Clan Nel Toth');
  const prop = Builder.completeMyDeck(Store.deckView(partial.id));
  ok(!prop.error && prop.needed > 0, 'proposal generated (' + prop.needed + ' needed)');
  ok(prop.adds.length + prop.basics.reduce((s, b) => s + b.q, 0) === prop.needed, 'proposal fills exactly to 99');
  ok(prop.adds.every((a) => !a.role || a.role !== 'land'), 'spell adds are not lands');
  ok(prop.basics.every((b) => /^(Swamp|Forest|Wastes)$/.test(b.n)), 'basics match color identity');
  Store.deleteUserDeck(partial.id);
  const bres = Builder.build({ archKey: 'aristocrats', cmdIdx: 0, bracket: 3, useCollection: false, substitute: false, budget: 100 });
  const bcost = bres.cards.filter((c) => !c.basic).reduce((s, c) => s + (c.usd || 0) * c.q, 0) + (bres.commander.usd || 0);
  ok(bres.cards.reduce((s, c) => s + c.q, 0) === 99, 'budget build still exactly 99');
  ok(bcost <= 130, 'budget shaping lands near the ceiling ($' + bcost.toFixed(0) + ' vs $100 cap)');

  // ---------- builder grid ----------
  section('BUILDER');
  ok(Builder.allCommanders().length >= 600, 'allCommanders serves the directory');
  const found = Builder.findCommander('Meren of Clan Nel Toth');
  ok(!!found, 'findCommander resolves');
  ok(found && Builder.fittingArchetypes(found).length > 0, 'fittingArchetypes returns options');
  let gridPass = 0, gridFail = 0;
  const T2 = window.VAULT_TEMPLATES;
  for (let ai = 0; ai < T2.archetypes.length; ai++) {
    for (const br of [2, 3, 4]) {
      try {
        const r = Builder.build({ archKey: T2.archetypes[ai].key, cmdIdx: 0, bracket: br, useCollection: false, substitute: false });
        const n = r.cards ? r.cards.reduce((s, c) => s + (c.q || 1), 0) : 0;
        const gcCount = r.cards ? r.cards.filter((c) => Rules.GAME_CHANGERS.some((g) => g.toLowerCase() === c.n.toLowerCase())).length : 0;
        const gcOk = br === 2 ? gcCount === 0 : br === 3 ? gcCount <= 3 : true;
        if (!r.error && n === 99 && gcOk) gridPass++;
        else { gridFail++; console.log('  grid fail:', T2.archetypes[ai].key, 'B' + br, r.error || ('n=' + n + ' gc=' + gcCount)); }
      } catch (e) { gridFail++; console.log('  grid throw:', T2.archetypes[ai].key, 'B' + br, e.message); }
    }
  }
  ok(gridFail === 0, 'build grid clean (' + gridPass + ' combos)');

  // ---------- views: full data ----------
  section('VIEWS');
  const deckId = meren.id;
  const sess = Store.state.sessions[0];
  const views = [
    ['dashboard', () => UI.viewDashboard({})],
    ['collection', () => UI.viewCollection({})],
    ['decks', () => UI.viewDecks()],
    ['mydeck', () => UI.viewMyDeck(deckId)],
    ['moves', () => UI.viewMoves()],
    ['import', () => UI.viewImport()],
    ['session', () => sess ? UI.viewSession(sess.id) : 'skip'.padEnd(60, '.')],
    ['guide', () => UI.viewGuide()],
    ['data', () => UI.viewData()],
    ['build', () => UI.viewBuild({})],
    ['pilot', () => UI.viewPilot()],
  ];
  for (const [name, fn] of views) {
    try { const h = fn(); ok(typeof h === 'string' && h.length > 50, 'view ' + name + ' renders (' + (h || '').length + ')'); }
    catch (e) { ok(false, 'view ' + name + ' threw: ' + e.message); }
  }

  // ---------- views: lazy state (heavy bundles absent) ----------
  const saved = { b: window.VAULT_BRAIN, t: window.VAULT_TEMPLATES, v: window.VAULT_VECTORS, c: window.VAULT_COMMANDERS };
  window.VAULT_BRAIN = undefined; window.VAULT_TEMPLATES = undefined; window.VAULT_VECTORS = undefined; window.VAULT_COMMANDERS = undefined;
  for (const name of ['dashboard', 'build', 'guide', 'mydeck']) {
    try {
      const h = name === 'mydeck' ? UI.viewMyDeck(deckId) : name === 'build' ? UI.viewBuild({}) : name === 'guide' ? UI.viewGuide() : UI.viewDashboard({});
      ok(typeof h === 'string' && h.length > 20, 'lazy view ' + name + ' renders');
    } catch (e) { ok(false, 'lazy view ' + name + ' threw: ' + e.message); }
  }
  Object.assign(window, { VAULT_BRAIN: saved.b, VAULT_TEMPLATES: saved.t, VAULT_VECTORS: saved.v, VAULT_COMMANDERS: saved.c });

  // ---------- micro-brains + coach ----------
  section('CMDCARDS');
  const CC = window.VAULT_CMDCARDS;
  ok(CC && Object.keys(CC.cmds).length >= 600, 'micro-brains cover 600+ commanders (' + (CC && Object.keys(CC.cmds).length) + ')');
  const sig = Builder.signatureFor('Meren of Clan Nel Toth', new Set(), 8);
  ok(sig.length === 8 && sig.every((s) => s.n && (s.syn > 0 || s.inc > 0)), 'signatureFor returns scored cards');
  const sigEx = Builder.signatureFor('Meren of Clan Nel Toth', new Set([Store.norm(sig[0].n)]), 8);
  ok(!sigEx.some((s) => s.n === sig[0].n), 'signatureFor respects exclusions');
  ok(rep.commanderSignature && rep.commanderSignature.length > 0, 'analyzer surfaces commander signature cards');
  const coachViews = UI.viewCoach();
  ok(typeof coachViews === 'string' && coachViews.includes('coach-deck'), 'coach view renders');

  // ---------- pilot model ----------
  section('PILOT');
  const pm = Pilot.model(Store.deckView(deckId), rep);
  ok(Array.isArray(pm.subThemes), 'pilot exposes sub-themes');
  ok(Pilot.OVERLAYS.length >= 10, '10 sub-archetype overlays authored (' + Pilot.OVERLAYS.length + ')');
  const eqO = Pilot.OVERLAYS.find((o) => o.key === 'equipment');
  ok(eqO && eqO.test(() => 0, (t) => (t === 'Equipment' ? 7 : 0)), 'equipment overlay triggers on type count');
  const reO = Pilot.OVERLAYS.find((o) => o.key === 'reanimator');
  ok(reO && reO.test((list) => list.filter((n) => ['Animate Dead', 'Reanimate'].includes(n)).length, () => 0), 'reanimator overlay triggers on names');
  ok(Pilot.OVERLAYS.every((o) => o.add && o.tips.length >= 2), 'every overlay carries plan text and tips');
  ok(pm && /^\d to \d$/.test(pm.landTarget), 'pilot opening-hand land guidance present (' + (pm && pm.landTarget) + ')');
  ok(pm.keyCards && pm.keyCards.length >= 3, 'pilot key cards identified');
  ok(pm.plan && pm.plan.length > 40, 'pilot has a game plan');
  ok(pm.strengths && pm.strengths.length > 0 && pm.weaknesses && pm.weaknesses.length > 0, 'pilot matchup notes present');

  // ---------- sync crypto (no network) ----------
  section('SYNC');
  const payload = { hello: 'vault', n: 42 };
  const env = await Sync.encrypt('Keanen', '1234', payload);
  const back = await Sync.decrypt('Keanen', '1234', env);
  ok(back.hello === 'vault' && back.n === 42, 'encrypt/decrypt roundtrip');
  let wrongPin = false;
  try { await Sync.decrypt('Keanen', '9999', env); } catch (e) { wrongPin = true; }
  ok(wrongPin, 'wrong PIN cannot decrypt');
  const s1 = await Sync.slugFor('Keanen', '1234');
  const s2 = await Sync.slugFor('keanen ', '1234');
  const s3 = await Sync.slugFor('Keanen', '5678');
  ok(s1 === s2 && s1 !== s3 && s1.length === 24, 'slug deterministic, case/space-insensitive, pin-sensitive');
  // full-size vault: a real collection is megabytes; byte-spreading overflowed the stack here once
  const big = { rows: Array.from({ length: 20000 }, (_, i) => ({ n: 'Card Number ' + i, q: 1 + (i % 4), b: 'Binder ' + (i % 9), usd: (i % 400) / 4 })) };
  const bigEnv = await Sync.encrypt('Keanen', '1234', big);
  const bigBack = await Sync.decrypt('Keanen', '1234', bigEnv);
  ok(bigBack.rows.length === 20000 && bigBack.rows[19999].n === 'Card Number 19999', 'megabyte-scale vault roundtrips (' + Math.round(bigEnv.ct.length / 1024) + 'KB ciphertext)');

  console.log('\n' + pass + ' passed, ' + fail + ' failed');
  process.exit(fail ? 1 : 0);
})().catch((e) => { console.error('SUITE CRASH:', e); process.exit(1); });
